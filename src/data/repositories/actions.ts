import { boolInt, bool, str, SqliteRepository } from '@/data/repository';
import type { RepositoryOptions } from '@/data/repository';
import type { Action, ActionType } from '@/data/types';
import type { ActionStatus, LegalStatus, RescueStatus } from '@/theme/status';

const options: RepositoryOptions<Action> = {
  table: 'actions',
  idField: 'actionId',
  sheet: 'Actions',
  rowToEntity: (row): Action => ({
    actionId: str(row.actionId),
    caseId: str(row.caseId),
    type: str(row.type, 'rescue') as ActionType,
    actionStatus: str(row.actionStatus, 'to_attend') as ActionStatus,
    rescueStatus: str(row.rescueStatus, 'na') as RescueStatus,
    legalStatus: str(row.legalStatus, 'na') as LegalStatus,
    assignedToId: str(row.assignedToId, 'self'),
    assignedToName: str(row.assignedToName, 'Self'),
    followUpById: str(row.followUpById, 'self'),
    followUpByName: str(row.followUpByName, 'Self'),
    nextAction: str(row.nextAction),
    followUpDate: row.followUpDate ? str(row.followUpDate) : null,
    dueValue: row.dueValue ? str(row.dueValue) : null,
    isClosed: bool(row.isClosed),
    closedAt: row.closedAt ? str(row.closedAt) : null,
    closedReason: str(row.closedReason),
    animalCondition: str(row.animalCondition),
    outcome: str(row.outcome),
    policeStation: str(row.policeStation),
    complaintDate: row.complaintDate ? str(row.complaintDate) : null,
    firNumber: str(row.firNumber),
    firDate: row.firDate ? str(row.firDate) : null,
    investigatingOfficerId: str(row.investigatingOfficerId),
    investigatingOfficerName: str(row.investigatingOfficerName),
    court: str(row.court),
    courtCaseNumber: str(row.courtCaseNumber),
    createdAt: str(row.createdAt),
    updatedAt: str(row.updatedAt),
    syncedAt: row.syncedAt ? str(row.syncedAt) : null,
    localVersion: Number(row.localVersion ?? 1),
    serverVersion: Number(row.serverVersion ?? 0),
    isDeleted: bool(row.isDeleted),
  }),
  entityToRow: (entity): Record<string, unknown> => ({
    actionId: entity.actionId,
    caseId: entity.caseId,
    type: entity.type,
    actionStatus: entity.actionStatus,
    rescueStatus: entity.rescueStatus,
    legalStatus: entity.legalStatus,
    assignedToId: entity.assignedToId,
    assignedToName: entity.assignedToName,
    followUpById: entity.followUpById,
    followUpByName: entity.followUpByName,
    nextAction: entity.nextAction,
    followUpDate: entity.followUpDate,
    dueValue: entity.dueValue,
    isClosed: boolInt(entity.isClosed),
    closedAt: entity.closedAt,
    closedReason: entity.closedReason,
    animalCondition: entity.animalCondition,
    outcome: entity.outcome,
    policeStation: entity.policeStation,
    complaintDate: entity.complaintDate,
    firNumber: entity.firNumber,
    firDate: entity.firDate,
    investigatingOfficerId: entity.investigatingOfficerId,
    investigatingOfficerName: entity.investigatingOfficerName,
    court: entity.court,
    courtCaseNumber: entity.courtCaseNumber,
    createdAt: entity.createdAt,
    updatedAt: entity.updatedAt,
    syncedAt: entity.syncedAt,
    localVersion: entity.localVersion,
    serverVersion: entity.serverVersion,
    isDeleted: boolInt(entity.isDeleted),
  }),
};

export const actionsRepository = new SqliteRepository<Action>(options);
